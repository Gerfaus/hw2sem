## 7. Написать код для создания срезов массива 3 на 4
## - первые две строки и три столбца
## - первые три строки и второй столбец
## - все строки и столбцы в обратном порядке
## - второй столбец
## - третья строка


a = np.arange(12).reshape(3, 4)
print(a)

# первые две строки и три столбца
print(a[:2, :3])

# первые три строки и второй столбец
print(a[:3, 1])

# все строки и столбцы в обратном порядке
print(a[::-1, ::-1])

# второй столбец
print(a[:, 1])

# третья строка
print(a[2, :])


