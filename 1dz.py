## 11. Разберитесь, как работают методы split, vsplit, hsplit, dsplit


a = np.arange(16).reshape(4, 4)
print(a)

# Разделить на две части по вертикали
b = np.vsplit(a, 2)
print(b)

# Разделить на две части по горизонтали
c = np.hsplit(a, 2)
print(c)

# split с указанием индексов
d = np.split(a, [1, 3], axis=1)  # split по столбцам, разделение перед 1 и 3 столбцами
print(d)


a = np.arange(27).reshape(3, 3, 3)  # Создаем трехмерный массив
b = np.dsplit(a, 3)  # Разбиваем по третьей оси на 3 части
print(b)


