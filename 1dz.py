## 1. Какие еще существуют коды типов?

#  'b': Signed char (целое число со знаком, 1 байт)
#  'B': Unsigned char (целое число без знака, 1 байт)
#  'h': Signed short (целое число со знаком, 2 байта)
#  'H': Unsigned short (целое число без знака, 2 байта)
#  'i': Signed int (целое число со знаком, зависит от системы, обычно 4 байта)
#  'I': Unsigned int (целое число без знака, зависит от системы, обычно 4 байта)
#  'l': Signed long (целое число со знаком, зависит от системы, обычно 4 или 8 байт)
#  'L': Unsigned long (целое число без знака, зависит от системы, обычно 4 или 8 байт)
#  'f': Float (число с плавающей точкой, обычно 4 байта)
#  'd': Double (число с плавающей точкой двойной точности, обычно 8 байт)


